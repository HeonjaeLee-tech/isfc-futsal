# -*- coding: utf-8 -*-
"""Phosphor Icons(@phosphor-icons/core, MIT)에서 쓰는 아이콘만 골라 SVG 스프라이트(assets/js/icons.js)로 만든다."""
import re, sys, json, pathlib

ASSETS = pathlib.Path(sys.argv[1])  # .../node_modules/@phosphor-icons/core/assets
OUT = pathlib.Path(sys.argv[2])

REGULAR = """map-pin soccer-ball trophy users-three gift fork-knife beer-stein megaphone car
person-simple-walk clock calendar-blank map-trifold arrow-square-out caret-right caret-down x warning
medal broadcast flag-checkered timer coins barricade copy check lock-simple t-shirt tree-structure
ranking info arrow-right navigation-arrow siren confetti receipt hourglass-medium magnifying-glass-plus
instagram-logo list-numbers crown-simple palette image pencil-simple trash
key toilet shuffle arrow-clockwise magnifying-glass door-open""".split()
FILL = "star soccer-ball trophy megaphone siren crown-simple map-pin car key sparkle".split()

def inner(path):
    s = path.read_text(encoding="utf-8")
    m = re.search(r"<svg[^>]*>(.*)</svg>", s, re.S)
    body = m.group(1).strip()
    body = re.sub(r"<rect width=\"256\" height=\"256\" fill=\"none\"/>", "", body)
    return body

symbols = []
for n in REGULAR:
    symbols.append(f'<symbol id="i-{n}" viewBox="0 0 256 256">{inner(ASSETS / "regular" / (n + ".svg"))}</symbol>')
for n in FILL:
    symbols.append(f'<symbol id="i-{n}-fill" viewBox="0 0 256 256">{inner(ASSETS / "fill" / (n + "-fill.svg"))}</symbol>')

sprite = '<svg xmlns="http://www.w3.org/2000/svg" style="position:absolute;width:0;height:0;overflow:hidden" aria-hidden="true">' + "".join(symbols) + "</svg>"
js = "/* Phosphor Icons (MIT) sprite, generated by tools/build_icons.py */\n" \
     "(function(){var d=document.createElement('div');d.innerHTML=" + json.dumps(sprite) + \
     ";document.body.insertBefore(d.firstChild,document.body.firstChild);})();\n"
OUT.write_text(js, encoding="utf-8")
print("icons:", len(symbols), "bytes:", len(js))
