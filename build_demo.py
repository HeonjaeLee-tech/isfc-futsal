        star = {"A3": 1, "B4": 2, "A1": 3}.get(m[side])
        weights = [14 if i == star else (4 if i in (1, 2) else 2) for i in range(len(roster))]
        for _ in range(cnt):
            goals.append({"경기번호": no, "선수": random.choices(roster, weights=weights)[0], "메모": ""})

